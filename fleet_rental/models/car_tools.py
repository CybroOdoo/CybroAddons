from odoo import fields, models


class CarTools(models.Model):
    """Model to add the tools for the car"""
    _name = 'car.tools'
    _description = "Car Tools"

    name = fields.Char(required=True, help='Name of the car tool')
    price = fields.Float(required=True, help='Price of the car tool')
