class IrUiMenu(models.Model):
    """Extend ir.ui.menu to link to dashboard menus."""
    _inherit = 'ir.ui.menu'

    dashboard_menu_id = fields.Many2one(
        'dashboard.menu',
        string='Dashboard Menu',
        help='Linked dashboard menu.'
    )
