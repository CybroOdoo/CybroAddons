from odoo import fields, models


class ResConfigSettings(models.TransientModel):
    """Add the table reservation option to the POS settings."""
    _inherit = 'res.config.settings'

    table_reservation = fields.Boolean(
        string="Table Reservation",
        related='pos_config_id.table_reservation',
        readonly=False,
        help="Allow reserving tables from the POS floor plan editor.")
