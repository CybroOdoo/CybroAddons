import json
import re

from odoo import http
from odoo.exceptions import AccessError
from odoo.fields import Domain
from odoo.http import request
from odoo.tools import file_open

_CSS_PARAM = 'backend_theme_infinito.dynamic_css'


def _check_admin():
    """Raise an error when the current user is not a Settings administrator."""
    if not request.env.user.has_group('base.group_system'):
        raise AccessError(request.env._('Only administrators can change the theme.'))


def _minify_css_string(css):
    css = re.sub(r'/\*[\s\S]*?\*/', "", css)
    css = re.sub(r'url\((["\'])([^)]*)\1\)', r'url(\2)', css)
    css = re.sub(r'\s+', ' ', css)
    css = re.sub(r'#([0-9a-f])\1([0-9a-f])\2([0-9a-f])\3(\s|;)', r'#\1\2\3\4', css)
    css = re.sub(r':\s*0(\.\d+([cm]m|e[mx]|in|p[ctx]))\s*;', r':\1;', css)
    rules = re.findall(r'([^{]+){([^}]*)}', css)
    selectors_list = []
    css_values = {}
    for rule in rules:
        selector = rule[0]
        content = rule[1]
        if selector not in selectors_list:
            selectors_list.append(selector)
            css_values[selector] = content
        else:
            css_values[selector] += ';' + content
    out = '/* Generated by Theme Infinito */\n'
    for selector in selectors_list:
        dict_rule = {}
        for r in css_values[selector].split(';'):
            if r:
                parts = r.split(':')
                if len(parts) == 2:
                    dict_rule[parts[0].strip()] = parts[1]
        out += selector + '{'
        for prop, val in dict_rule.items():
            if prop != 'pointer-events':
                if '!important' not in val:
                    out += prop + ':' + val + ' !important;'
                else:
                    out += prop + ':' + val + ';'
        out += '}'
    return out


class ThemeStudio(http.Controller):
    """Controller class for managing themes in a web application.

    This controller handles requests related to managing themes, such as
    applying themes, customizing themes, and saving theme settings.
    """

    @http.route(['/theme_studio/save_styles'], type="jsonrpc")
    def save_styles(self, kwargs):
        """Save dynamic styles for an object class (administrators only).

        Args:
            kwargs (dict): Contains 'changed_styles' (a JSON string of CSS
                properties) and 'object_class' (the class name).

        Returns:
            bool: True when the styles are saved.
        """
        _check_admin()
        changed_styles_str = kwargs.get('changed_styles', '{}')
        object_class = kwargs.get('object_class', '')
        changed_styles = json.loads(changed_styles_str)
        IrConfigParam = request.env['ir.config_parameter'].sudo()
        css = IrConfigParam.get_param(_CSS_PARAM, default='')
        css += '\n.' + object_class + ' {\n'
        for prop, val in changed_styles.items():
            css += '\t' + prop + ': ' + val + ';\n'
        css += '}\n'
        IrConfigParam.set_param(_CSS_PARAM, _minify_css_string(css))
        return True

    @http.route(['/theme_studio/get_current_style'], type="jsonrpc")
    def get_current_style(self, kwargs):
        """Return the saved style properties of a CSS selector.

        Args:
            kwargs (dict): Contains the 'selector' key.

        Returns:
            list or bool: A list of [property, value] pairs, or False when
            the selector is not found.
        """
        selector = kwargs.get('selector', '')
        IrConfigParam = request.env['ir.config_parameter'].sudo()
        css = IrConfigParam.get_param(_CSS_PARAM, default='')
        css = re.sub(r'/\*[\s\S]*?\*/', "", css)
        css = re.sub(r'url\((["\'])([^)]*)\1\)', r'url(\2)', css)
        css = re.sub(r'\s+', ' ', css)
        css = re.sub(r'#([0-9a-f])\1([\da-f])\2([0-9a-f])\3(\s|;)', r'#\1\2\3\4', css)
        css = re.sub(r':\s*0(\.\d+([cm]m|e[mx]|in|p[ctx]))\s*;', r':\1;', css)
        rules = re.findall(r'([^{]+){([^}]*)}', css)
        for rule in rules:
            selector_now = rule[0]
            content = rule[1]
            if selector == selector_now.strip():
                result = []
                for c in content.split(';'):
                    parts = c.split(':')
                    if parts[0] != '' and len(parts) > 1:
                        result.append([parts[0], parts[1].replace('!important', '').strip()])
                return result
        return False

    @http.route(['/theme_studio/reset_to_default'], type="jsonrpc")
    def reset_to_default(self):
        """Clear all dynamic styles (administrators only).

        Returns:
            bool: True when the styles are reset.
        """
        _check_admin()
        request.env['ir.config_parameter'].sudo().set_param(_CSS_PARAM, '')
        return True

    @http.route(['/backend_theme_infinito/dynamic_styles.css'], type='http', auth='public')
    def serve_dynamic_styles(self):
        """Serve the saved dynamic styles as a stylesheet."""
        css = request.env['ir.config_parameter'].sudo().get_param(_CSS_PARAM, default='')
        return request.make_response(
            css,
            headers=[
                ('Content-Type', 'text/css; charset=utf-8'),
                ('Cache-Control', 'no-cache, no-store, must-revalidate'),
            ]
        )

    @http.route(['/theme_studio/set_advanced_data'], type="jsonrpc")
    def set_advanced_data(self, args):
        """Save the global advanced theme options (administrators only).

        Args:
            args (list): A list holding a dictionary with the key 'vals'.

        Returns:
            bool: True when the options are saved, otherwise False.
        """
        _check_admin()
        if args and 'vals' in args[0]:
            vals = args[0]['vals']
            IrConfigParam = request.env['ir.config_parameter'].sudo()
            IrConfigParam.set_param('backend_theme_infinito.is_user_edit', vals.get('userEdit', False))
            IrConfigParam.set_param('backend_theme_infinito.loader_class', vals.get('loaderClass', 'default'))
            IrConfigParam.set_param('backend_theme_infinito.dark_start', vals.get('infinitoDarkStart', 19.0))
            IrConfigParam.set_param('backend_theme_infinito.dark_end', vals.get('infinitoDarkEnd', 5.0))
            IrConfigParam.set_param('backend_theme_infinito.is_sidebar_enabled', vals['sidebar'])
            IrConfigParam.set_param('backend_theme_infinito.is_fullscreen_enabled', vals['fullscreen'])
            IrConfigParam.set_param('backend_theme_infinito.is_sidebar_icon', vals['sidebarIcon'])
            IrConfigParam.set_param('backend_theme_infinito.is_sidebar_name', vals['sidebarName'])
            IrConfigParam.set_param('backend_theme_infinito.is_sidebar_company', vals['sidebarCompany'])
            IrConfigParam.set_param('backend_theme_infinito.is_sidebar_user', vals['sidebarUser'])
            IrConfigParam.set_param('backend_theme_infinito.is_recent_apps', vals['recentApps'])
            IrConfigParam.set_param('backend_theme_infinito.is_fullscreen_app', vals['fullScreenApp'])
            IrConfigParam.set_param('backend_theme_infinito.is_rtl', vals['infinitoRtl'])
            IrConfigParam.set_param('backend_theme_infinito.is_dark', vals['infinitoDark'])
            IrConfigParam.set_param('backend_theme_infinito.dark_mode', vals['infinitoDarkMode'])
            IrConfigParam.set_param('backend_theme_infinito.is_menu_bookmark', vals['infinitoBookmark'])
            return True
        return False

    @http.route(['/theme_studio/set_advanced_data_user'], type="jsonrpc")
    def set_advanced_data_user(self, args):
        """Save the advanced theme options of the current user.

        Args:
            args (list): A list holding a dictionary with the key 'vals'.

        Returns:
            bool: True when the options are saved, otherwise False.
        """
        if args and 'vals' in args[0]:
            vals = args[0]['vals']
            request.env.user.write({
                'is_sidebar_enabled': vals['sidebar'],
                'is_fullscreen_enabled': vals['fullscreen'],
                'is_sidebar_icon': vals['sidebarIcon'],
                'is_sidebar_name': vals['sidebarName'],
                'is_sidebar_company': vals['sidebarCompany'],
                'is_sidebar_user': vals['sidebarUser'],
                'is_recent_apps': vals['recentApps'],
                'is_fullscreen_app': vals['fullScreenApp'],
                'is_rtl': vals['infinitoRtl'],
                'is_dark': vals['infinitoDark'],
                'dark_mode': vals['infinitoDarkMode'],
                'is_menu_bookmark': vals['infinitoBookmark'],
                'loader_class': vals['loaderClass']
            })
            return True
        return False

    @http.route(['/theme_studio/add_recent_app'], type="jsonrpc")
    def add_recent_app(self, args):
        """Add an application to the recent apps of the current user.

        Keeps at most five recent apps: the oldest one is removed when the
        limit is reached.

        Args:
            args (list): A list holding a dictionary with the key 'appId'.
        """
        if args and isinstance(args, list) and len(args) > 0:
            app_id = args[0].get('appId')
            if app_id is not None:
                app_id = int(app_id)
            else:
                app_id = 0
        else:
            app_id = 0

        recent_app = request.env['recent.apps'].sudo()
        exist = recent_app.search([
            ('app_id', '=', app_id),
            ('user_id', '=', request.env.user.id)
        ])
        exist.unlink() if exist else None
        total_recent = recent_app.search(
            [('user_id', '=', request.env.user.id)])
        if len(total_recent) > 4:
            total_recent[0].unlink()
        recent_app.create({
            'app_id': app_id,
            'user_id': request.env.user.id
        })

    @http.route(['/theme_studio/get_recent_apps'], type="jsonrpc")
    def get_recent_apps(self):
        """Return the recent applications of the current user.

        Returns:
            list: A list of dictionaries, one for each recent application.
        """
        recent_app = request.env['recent.apps'].sudo()
        return recent_app.search_read([
            ('user_id', '=', request.env.user.id)
        ])

    @http.route(['/theme_studio/add_menu_bookmarks'], type="jsonrpc")
    def add_menu_bookmarks(self, args):
        """Add or update a menu bookmark for the current user.

        Args:
            args (dict): Contains a 'menu' dictionary with 'actionId',
                'menuId', 'menuUrl' and 'name'.

        Returns:
            bool: True when the bookmark is saved, otherwise False.
        """
        menu_data = args.get('menu', {})
        action_id = menu_data.get('actionId')
        menu_id = menu_data.get('menuId')
        user_id = request.env.user.id
        url = menu_data.get('menuUrl')
        name = menu_data.get('name')
        menu = request.env['ir.ui.menu'].sudo()
        menu_record = menu.browse(int(menu_id)) if menu_id else menu.browse()
        if menu_record and not menu_record.exists():
            menu_record = menu.browse()
        if not name and menu_record:
            name = menu_record.name
        if not name and action_id:
            action = request.env['ir.actions.actions'].sudo().browse(int(action_id))
            if action.exists():
                name = action.name
        menu_bookmark = request.env['infinito.menu.bookmark'].sudo()
        menu_domain = [('menu_id', '=', menu_record.id)] if menu_record else []
        url_domain = [('url', '=', url)] if url else []
        if menu_domain and url_domain:
            domain = Domain.AND([
                [('user_id', '=', user_id)],
                Domain.OR([menu_domain, url_domain]),
            ])
        elif menu_domain:
            domain = [('user_id', '=', user_id)] + menu_domain
        elif url_domain:
            domain = [('user_id', '=', user_id)] + url_domain
        elif action_id:
            domain = [('user_id', '=', user_id), ('action_id', '=', int(action_id))]
        else:
            return False
        existing_bookmark = menu_bookmark.search(domain, limit=1)
        if existing_bookmark:
            existing_bookmark.write({
                'action_id': int(action_id) if action_id else existing_bookmark.action_id.id,
                'menu_id': menu_record.id if menu_record else existing_bookmark.menu_id.id,
                'url': url or existing_bookmark.url,
                'name': name or existing_bookmark.name or 'Bookmark',
            })
            return True
        menu_bookmark.create({
            'action_id': int(action_id) if action_id else False,
            'menu_id': menu_record.id if menu_record else False,
            'user_id': user_id,
            'url': url,
            'name': name or 'Bookmark',
        })
        return True

    @http.route(['/theme_studio/remove_menu_bookmarks'], type="jsonrpc")
    def remove_menu_bookmarks(self, args):
        """Remove a menu bookmark of the current user.

        Args:
            args (dict): Contains a 'menu' dictionary with 'actionId',
                'menuId' and 'menuUrl'.

        Returns:
            bool: True when the bookmark is removed, otherwise False.
        """
        menu_data = args.get('menu', {})
        action_id = menu_data.get('actionId')
        menu_id = menu_data.get('menuId')
        url = menu_data.get('menuUrl')
        user_id = request.env.user.id
        if menu_id and url:
            domain = Domain.AND([
                [('user_id', '=', user_id)],
                Domain.OR([
                    [('menu_id', '=', int(menu_id))],
                    [('url', '=', url)],
                ]),
            ])
        elif menu_id:
            domain = [('user_id', '=', user_id), ('menu_id', '=', int(menu_id))]
        elif url:
            domain = [('user_id', '=', user_id), ('url', '=', url)]
        elif action_id:
            domain = [('user_id', '=', user_id), ('action_id', '=', int(action_id))]
        else:
            return False
        menu_bookmark = request.env['infinito.menu.bookmark'].sudo().search(domain)
        if menu_bookmark:
            menu_bookmark.unlink()
        return True

    @http.route(['/theme_studio/get_presets'], type="jsonrpc")
    def get_presets(self):
        """Return the list of available presets from the presets file."""
        with file_open('backend_theme_infinito/static/src/json/presets.json') as presets_file:
            return json.load(presets_file)