from odoo import fields, models


class WmSignature(models.Model):
    """Stores a captured digital signature (image + timestamp) for a collection order handover acknowledgement."""
    _name = 'wm.signature'
    _description = 'Signature'
    _inherit = ['mail.thread', 'mail.activity.mixin']

    name = fields.Char('Name')
    signature = fields.Binary('Signature Image')
