/** @odoo-module **/
import { ControlButtons } from "@point_of_sale/app/screens/product_screen/control_buttons/control_buttons";
import { patch } from "@web/core/utils/patch";
import { _t } from "@web/core/l10n/translation";
import { useService } from "@web/core/utils/hooks";

patch(ControlButtons.prototype, {
    setup() {
        super.setup(...arguments);
        this.takeAwayNotification = useService("notification");
    },
    get isTakeAwayOrder() {
        return Boolean(this.pos.getOrder()?.is_takeaway);
    },
    get takeAwayButtonClass() {
        return this.isTakeAwayOrder ? "btn-primary" : "btn-light";
    },
    onClickTakeAway() {
        const order = this.pos.getOrder();
        if (!order) {
            return;
        }
        if (!order.lines.length) {
            this.takeAwayNotification.add(_t("Please add a product first."), {
                type: "warning",
            });
            return;
        }
        // The token is generated by the server when the order is synchronised.
        order.is_takeaway = !order.is_takeaway;
    },
});
