from odoo import fields, models

class PosConfig(models.Model):
    _inherit = 'pos.config'

    is_add_pos_payment_reference = fields.Boolean(string="Add Payment Reference")

    def _load_pos_data_fields(self, config_id):
        params = super()._load_pos_data_fields(config_id)
        if params:
            params.append('is_add_pos_payment_reference')
        return params
