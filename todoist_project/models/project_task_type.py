    """Extends project.task.type to store Todoist section ID."""
    _inherit = 'project.task.type'

    todo_stage = fields.Char(
        string='Todoist Section ID',
        help='Stores the Todoist section ID mapped to this Odoo stage.',
        copy=False,
    )
