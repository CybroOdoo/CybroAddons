import base64
import logging
import re
from io import BytesIO

import qrcode
from markupsafe import Markup
from werkzeug.urls import url_encode

from odoo import Command, api, fields, models
from odoo.exceptions import ValidationError

_logger = logging.getLogger(__name__)

# Seat ids are generated by the seat selection template as R<row>C<column>.
SEAT_ID_RE = re.compile(r'^R([1-9]\d*)C([1-9]\d*)$')


def _to_int(value):
    """ Cast to int, 0 when it is not a valid number (browse(0) is empty). """
    try:
        return int(value)
    except (TypeError, ValueError):
        return 0


class MovieRegistration(models.Model):
    """
        Model for managing movie registrations including details like partner,
        movie, date, time slot, screen, tickets, etc.
    """
    _name = 'movie.registration'
    _description = 'Movie Registration'

    name = fields.Char(required=True, copy=False,
                       default='New', readonly=True,
                       help='Name of the Movie Ticket')
    partner_id = fields.Many2one('res.partner', string='Select Partner',
                                 help='Mention the partner')
    movie_id = fields.Many2one('movie.movie', string='Select Movie',
                               domain="[('id', 'in', available_movie_ids)]",
                               required=True, help='Mention the movie id')
    show_type_ids = fields.Many2many(related='movie_id.show_type_ids',
                                     string='Show Type',
                                     help='Show type of the movie')
    movie_language_id = fields.Many2one(related='movie_id.movie_language_id',
                                        string='Movie Language',
                                        help='Language of the movie')
    date = fields.Date(default=fields.Date.context_today,
                       required=True, help='Mention the date for booking.')
    time_slot_id = fields.Many2one('time.slots',
                                   string='Select time slot',
                                   domain="[('id', 'in', available_time_slot_ids)]",
                                   required=True, help='Mention the time slots of the movie')
    screen_id = fields.Many2one('movie.screen', string='Select Screen',
                                domain="[('id', 'in', available_screens_ids)]",
                                required=True, help='Mention the screen of the movie')
    available_movie_ids = fields.Many2many('movie.movie',
                                           string='Available movies',
                                           help='Mention the available movies')
    available_time_slot_ids = fields.Many2many('time.slots',
                                               string='Available time slots',
                                               compute='_compute_available_time_slot_ids',
                                               help='Mention the available time slots')
    available_screens_ids = fields.Many2many('movie.screen',
                                             string='Available screens',
                                             compute='_compute_available_time_slot_ids',
                                             help='Mention the available screen')
    movie_price = fields.Monetary(string='Movie Price',
                                  related='movie_id.price',
                                  help='Price of the movie ticket')
    currency_id = fields.Many2one('res.currency', help="Currency",
                                  required=True,
                                  default=lambda
                                      self: self.env.user.company_id.currency_id)
    no_of_tickets = fields.Integer(string='Number of tickets', default=1,
                                   help='Mention the number of tickets')
    movie_poster = fields.Binary(related='movie_id.movie_poster',
                                 string='Movie poster',
                                 help='Poster of the movie.')
    movie_cast_ids = fields.Many2many(related='movie_id.movie_cast_ids',
                                      string='Movie Cast', readonly=True,
                                      help='Movie casts')
    seat_ids = fields.One2many('movie.seats', 'movie_registration_id',
                               string="Seats", help='Mention the seat ids')
    qr_code = fields.Binary(help='Qr code containing ticket details')
    state = fields.Selection([('draft', 'Draft'),
                              ('invoiced', 'Invoiced')], string='Status',
                             default='draft', help='Status of the movie registration')

    def action_select_seats(self):
        """ Function for redirecting to seat selection page on website."""
        self.ensure_one()
        if not self.movie_id or not self.date or not self.time_slot_id or not self.screen_id:
            raise ValidationError(self.env._('Please select the movie, date, time slot and screen first.'))

        params = {
            'movie_id': self.movie_id.id,
            'screen': self.screen_id.id,
            'time_slots': self.time_slot_id.id,
            'show_date': self.date,
            'registration_id': self.id,
        }
        return {
            'type': 'ir.actions.act_url',
            'url': f'/movie/book_ticket?{url_encode(params)}',
            'target': 'new',
        }

    @api.depends('movie_id')
    def _compute_available_time_slot_ids(self):
        """ Function for computing the time slots and screens of the movie."""
        for record in self:
            record.available_time_slot_ids = record.movie_id.available_time_slots_ids
            record.available_screens_ids = record.movie_id.available_screens_ids

    @api.onchange('date')
    def _onchange_date(self):
        """ Function for validating date and fetching movies based on the date."""
        for record in self:
            if record.date < fields.Date.context_today(self):
                raise ValidationError(self.env._("The date must be today or later."))
            record.movie_id = None
            record.available_movie_ids = None
            movies_list = self.env['movie.movie'].search([
                ('show_start_date', '<=', record.date),
                ('show_end_date', '>=', record.date),
                '|', ('state', '=', 'ongoing'),
                '&', ('state', '=', 'prebooking'),
                ('booking_end_date', '=', False)
            ]).ids
            record.available_movie_ids = movies_list

    def check_seat_availability(self):
        """ Function for checking seat availability"""
        reserved_seats = sum(self.search([
            ('id', '!=', self.id),
            ('date', '=', self.date),
            ('time_slot_id', '=', self.time_slot_id.id),
            ('screen_id', '=', self.screen_id.id),
            ('state', '=', 'invoiced')
        ]).mapped('no_of_tickets')) + self.no_of_tickets
        if reserved_seats > self.screen_id.total_seat_count:
            raise ValidationError(self.env._('The selected screen is already full.'))

        # Pre-booking limit check
        if self.movie_id.state == 'prebooking' and self.movie_id.prebooking_slot > 0:
            if reserved_seats > self.movie_id.prebooking_slot:
                raise ValidationError(self.env._(
                    'Pre-booking limit reached. Only %s seats are allowed for pre-booking.',
                    self.movie_id.prebooking_slot))

    @api.model_create_multi
    def create(self, vals_list):
        """Supering create function to check screen availability"""
        for vals in vals_list:
            if vals.get('name', 'New') == 'New':
                vals['name'] = self.env['ir.sequence'].next_by_code(
                    'movie.registration')
        res = super().create(vals_list)
        for record in res:
            record.check_seat_availability()
        return res

    @api.constrains('no_of_tickets', 'seat_ids')
    def check_seat(self):
        """ Function for checking seat availability based on the number of tickets"""
        for record in self:
            if record.no_of_tickets <= 0:
                raise ValidationError(self.env._('The number of tickets must be at least 1.'))
            if record.seat_ids and len(record.seat_ids) != record.no_of_tickets:
                raise ValidationError(self.env._(
                    'The number of selected seats (%(seats)s) does not match '
                    'the number of tickets (%(tickets)s).',
                    seats=len(record.seat_ids), tickets=record.no_of_tickets))
            record.check_seat_availability()

    @api.onchange('movie_id')
    def _onchange_movie_id(self):
        """ Function for resetting time slot and screen while changing movie."""
        for record in self:
            record.update({'time_slot_id': None, 'screen_id': None})

    def action_generate_ticket_pdf(self):
        """ Function for downloading ticket pdf."""
        return self.env.ref(
            'show_booking_management.action_report_movie_ticket').report_action(self)

    def get_qr_code_image(self):
        """ Function for generating QR code image for the report """
        qr_data = f"Ticket : {self.name}\n" \
                  f"Movie: {self.movie_id.name}\n" \
                  f"Date: {self.date}\n" \
                  f"Time: {self.time_slot_id.name}\n" \
                  f"Screen: {self.screen_id.name}\n" \
                  f"Seats: {', '.join(self.seat_ids.mapped('seat'))}"
        qr = qrcode.QRCode(version=None,
                           error_correction=qrcode.constants.ERROR_CORRECT_L,
                           box_size=10, border=5)
        qr.add_data(qr_data)
        qr.make(fit=True)
        img = qr.make_image()
        buffer = BytesIO()
        img.save(buffer, format="PNG")
        return base64.b64encode(buffer.getvalue())

    @api.model
    def check_seat_available(self, date, time_slot_id, screen_id, ticket_count):
        """ Function for updating the status of the seats availability based
         on the movie time slot and screen selected"""
        screen = self.env['movie.screen'].browse(int(screen_id))
        reserved_seats = sum(self.search([
            ('date', '=', date),
            ('time_slot_id', '=', int(time_slot_id)),
            ('screen_id', '=', int(screen_id)),
            ('state', '=', 'invoiced')
        ]).mapped('no_of_tickets'))
        if reserved_seats + int(ticket_count) > screen.total_seat_count:
            return {
                'Status': 'Failed',
                'Error': self.env._("The selected screen has only %s seats left.",
                           screen.total_seat_count - reserved_seats),
            }

        # Pre-booking limit check for frontend
        movie = self.env['movie.movie'].search([
            ('available_screens_ids', 'in', screen.id),
            ('available_time_slots_ids', 'in', int(time_slot_id)),
            ('show_start_date', '<=', date),
            ('show_end_date', '>=', date)
        ], limit=1)

        if movie and movie.state == 'prebooking' and movie.prebooking_slot > 0:
            if reserved_seats + int(ticket_count) > movie.prebooking_slot:
                return {
                    'Status': 'Failed',
                    'Error': self.env._("Only %(slot)s seats are allowed for pre-booking. "
                               "%(booked)s are already booked.",
                               slot=movie.prebooking_slot, booked=reserved_seats),
                }

        return {'Status': 'Success'}

    def action_open_invoices(self):
        """ Function for viewing created invoices"""
        return {
            'name': self.env._('Invoices'),
            'domain': [('movie_ticket_id', '=', self.id)],
            'res_model': 'account.move',
            'view_id': False,
            'view_mode': 'list,form',
            'type': 'ir.actions.act_window',
        }

    # -------------------------------------------------------------------------
    # Booking fulfilment (payment post-processing)
    # -------------------------------------------------------------------------
    @api.model
    def _fulfil_booking(self, invoice):
        """ Issue the ticket of a booking invoice once it is paid.

        Called from `payment.transaction._post_process`, so there is no HTTP
        request or session: everything comes from the invoice. The stored
        booking data is re-validated (never trusted), the price is recomputed
        from the show and the seat chart is protected by a row lock.

        Only the registration and seat writes are atomic. The QR code, the
        attachment and the email never raise: a failure is logged and the
        booking stays confirmed. If the booking cannot be confirmed (seat taken
        meanwhile, show cancelled, underpaid...) nothing is raised either: the
        invoice is flagged, a note is posted and staff are notified.

        Idempotent: does nothing when the invoice has no pending booking data
        or already has a ticket.

        :param account.move invoice: The paid booking invoice.
        :return: The ticket, or an empty recordset.
        :rtype: movie.registration
        """
        invoice = invoice.sudo()
        invoice.ensure_one()
        registration = self.sudo()
        if not invoice.movie_booking_data or invoice.movie_ticket_id:
            return registration.browse()
        if invoice.payment_state not in ('paid', 'in_payment'):
            return registration.browse()  # Partially paid: wait for the rest
        try:
            show = registration._validate_booking_data(invoice)
            with self.env.cr.savepoint():
                ticket = registration._create_ticket(invoice, show)
        except ValidationError as error:
            registration._notify_booking_issue(invoice, error.args[0])
            return registration.browse()
        ticket._issue_ticket_extras(invoice)
        return ticket

    def _validate_booking_data(self, invoice):
        """ Re-validate the booking data stored on the invoice, and check that
        the invoice covers the price recomputed from the show.

        :return: The validated values (see `_validate_booking_values`).
        :rtype: dict
        :raise ValidationError: If the booking can no longer be honoured.
        """
        show = self._validate_booking_values(invoice.movie_booking_data, lock=True)
        expected = show['movie'].currency_id._convert(
            show['movie'].price * len(show['seats']), invoice.currency_id, invoice.company_id,
            invoice.invoice_date or fields.Date.context_today(self))
        if invoice.currency_id.compare_amounts(invoice.amount_total, expected) < 0:
            raise ValidationError(self.env._(
                "The invoice (%(paid)s) does not cover the price of the seats (%(expected)s).",
                paid=invoice.amount_total, expected=expected))
        return show

    @api.model
    def _validate_booking_values(self, data, lock=False):
        """ Validate a booking request, whether it comes from the website form
        (`confirm_booking`) or from the data stored on an invoice (fulfilment).
        Nothing in `data` is trusted.

        With `lock`, a row lock is grabbed on the screen before the seats are
        checked, so two concurrent fulfilments of the same screen are
        serialized. It does not block foreign keys (FOR NO KEY UPDATE) and does
        not wait (SKIP LOCKED): if another fulfilment holds it, `LockError`
        propagates and core retries the post-processing from the cron.

        :param dict data: movie_id, screen_id, time_slot_id, booking_date,
            selected_seats and optional registration_id.
        :return: The validated records and values.
        :rtype: dict
        :raise ValidationError: If the booking is not acceptable.
        """
        if not isinstance(data, dict):
            raise ValidationError(self.env._("The booking data is malformed."))
        movie = self.env['movie.movie'].browse(_to_int(data.get('movie_id'))).exists()
        screen = self.env['movie.screen'].browse(_to_int(data.get('screen_id'))).exists()
        time_slot = self.env['time.slots'].browse(_to_int(data.get('time_slot_id'))).exists()
        if not (movie and screen and time_slot):
            raise ValidationError(self.env._("The show, screen or time slot no longer exists."))
        if lock:
            screen.lock_for_update(allow_referencing=True)
        try:
            date = fields.Date.to_date(data.get('booking_date'))
        except ValueError:
            date = None
        if not date:
            raise ValidationError(self.env._("The booking date is invalid."))
        if movie.state not in ('ongoing', 'prebooking'):
            raise ValidationError(self.env._("%s is no longer open for booking.", movie.name))
        if screen not in movie.available_screens_ids or time_slot not in movie.available_time_slots_ids:
            raise ValidationError(self.env._("The screen or time slot does not belong to %s.", movie.name))
        start, end = movie.show_start_date, movie.show_end_date
        if date < fields.Date.context_today(self) or not (start and end and start <= date <= end):
            raise ValidationError(self.env._("%(movie)s is not shown on %(date)s.", movie=movie.name, date=date))

        seats = data.get('selected_seats')
        if not isinstance(seats, list) or not seats or len(set(seats)) != len(seats):
            raise ValidationError(self.env._("The selected seats are invalid."))
        for seat in seats:
            match = isinstance(seat, str) and SEAT_ID_RE.match(seat)
            if not match or int(match[1]) > screen.total_rows or int(match[2]) > screen.no_of_seat_row:
                raise ValidationError(self.env._("Seat %(seat)s does not exist on %(screen)s.", seat=seat, screen=screen.name))
        taken = self.env['movie.seats'].search([
            ('screen_id', '=', screen.id), ('time_slot_id', '=', time_slot.id),
            ('date', '=', date), ('is_booked', '=', True), ('seat', 'in', seats),
        ]).mapped('seat')
        if taken:
            raise ValidationError(self.env._("Seat(s) %s already taken.", ", ".join(sorted(taken))))
        availability = self.check_seat_available(date, time_slot.id, screen.id, len(seats))
        if availability['Status'] != 'Success':
            raise ValidationError(availability['Error'])

        draft_ticket = self.browse()
        if data.get('registration_id'):
            draft_ticket = self.browse(_to_int(data['registration_id'])).exists()
            if not draft_ticket or draft_ticket.state != 'draft':
                raise ValidationError(self.env._("The booking to complete no longer exists or is already invoiced."))
        return {
            'movie': movie, 'screen': screen, 'time_slot': time_slot,
            'date': date, 'seats': seats, 'draft_ticket': draft_ticket,
        }

    def _create_ticket(self, invoice, show):
        """ Create (or complete) the registration and its seats, and close the
        pending booking of the invoice. Meant to run in a savepoint. """
        vals = {
            'movie_id': show['movie'].id,
            'screen_id': show['screen'].id,
            'time_slot_id': show['time_slot'].id,
            'date': show['date'],
            'no_of_tickets': len(show['seats']),
            'state': 'invoiced',
        }
        ticket = show['draft_ticket']
        if ticket:
            ticket.seat_ids.unlink()
            ticket.write(vals)
        else:
            ticket = self.create(dict(vals, partner_id=invoice.partner_id.id))
        self.env['movie.seats'].create([{
            'screen_id': show['screen'].id,
            'time_slot_id': show['time_slot'].id,
            'movie_registration_id': ticket.id,
            'date': show['date'],
            'seat': seat,
            'is_booked': True,
        } for seat in show['seats']])
        invoice.write({'movie_ticket_id': ticket.id, 'movie_booking_data': False})
        return ticket

    def _issue_ticket_extras(self, invoice):
        """ Generate the QR code and send the ticket. The seats are already
        booked: a failure here is logged and must never undo the booking. """
        self.ensure_one()
        attachment = self.env['ir.attachment']
        try:
            with self.env.cr.savepoint():
                # Binary fields take a base64 str (not bytes) and attachments
                # take raw bytes (`datas` was removed) in v20.
                qr_image = self.get_qr_code_image().decode()
                self.write({'qr_code': qr_image})
                attachment = self.env['ir.attachment'].create({
                    'name': 'Movie_Ticket_QR_Code.png',
                    'type': 'binary',
                    'raw': base64.b64decode(qr_image),
                    'res_model': 'movie.registration',
                    'res_id': self.id,
                    'mimetype': 'image/png',
                })
        except Exception:
            _logger.exception("Could not generate the QR code of ticket %s", self.name)
        try:
            with self.env.cr.savepoint():
                email_values = {'attachment_ids': [Command.set(attachment.ids)]}
                email_from = self._get_ticket_email_from(invoice.company_id)
                if email_from:
                    email_values['email_from'] = email_from
                self.env.ref('show_booking_management.email_template_movie_ticket').send_mail(
                    self.id, force_send=True, raise_exception=False, email_values=email_values)
        except Exception:
            _logger.exception("Could not send the email of ticket %s", self.name)

    @api.model
    def _get_booking_admin_users(self):
        """ Active users of the Show Booking Management administrator group. """
        admin_group = self.env.ref('show_booking_management.show_booking_management_group_admin')
        return self.env['res.users'].sudo().search([('group_ids', 'in', admin_group.id)])

    @api.model
    def _get_ticket_email_from(self, company):
        """ Sender of the ticket email: the first administrator with an email,
        else the company email (False when neither exists). """
        admins = self._get_booking_admin_users().filtered('email')
        return admins[:1].email or company.email or False

    @api.model
    def _notify_booking_issue(self, invoice, reason):
        """ A paid booking could not be confirmed: flag the invoice, post a note
        and notify the administrators (activity, else the company email).
        Done once per invoice. The pending booking data is kept for staff. """
        _logger.warning("Paid booking invoice %s could not be confirmed: %s", invoice.name, reason)
        if invoice.movie_booking_issue:
            return
        invoice.movie_booking_issue = True
        invoice.message_post(body=self.env._(
            "The invoice was paid but the booking could not be confirmed: %s "
            "The customer must be refunded or given other seats.", reason))
        admin = self._get_booking_admin_users()[:1]
        if admin:
            invoice.activity_schedule(
                'mail.mail_activity_data_todo',
                summary=self.env._("Paid movie booking not confirmed"),
                note=reason, user_id=admin.id)
        elif invoice.company_id.email:
            self.env['mail.mail'].create({
                'subject': self.env._("Paid movie booking not confirmed: %s", invoice.name),
                'body_html': Markup('<p>%s</p>') % self.env._(
                    "Invoice %(invoice)s was paid but the booking could not be confirmed: %(reason)s",
                    invoice=invoice.name, reason=reason),
                'email_to': invoice.company_id.email,
            }).send()
