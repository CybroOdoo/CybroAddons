from odoo.tests.common import TransactionCase

class TestVenueType(TransactionCase):

    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        cls.venue_type = cls.env['venue.type'].create({
            'name': 'Conference Hall'
        })

    def test_venue_type_creation(self):
        """Test venue type creation."""
        self.assertEqual(self.venue_type.name, 'Conference Hall')
