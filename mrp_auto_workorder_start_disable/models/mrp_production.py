from odoo import fields, models


class MrpProduction(models.Model):
    """This class inherits from 'mrp.production' and introduces a field to
    control the auto-start feature for work orders in tablet view."""
    _inherit = 'mrp.production'

    is_work_order = fields.Boolean(
        string="Auto start work order in tablet view",
        help="Enable to auto start work order.")
