from . import models


def _default_product_confirm(env):
    """Confirm products that already exist when the module is installed."""
    products = env['product.template'].with_context(
        active_test=False).search([('approve_state', '!=', 'confirmed')])
    products.write({'approve_state': 'confirmed'})
