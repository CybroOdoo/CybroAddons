from odoo.tests import TransactionCase, tagged


@tagged('post_install', '-at_install')
class TestCashBookReport(TransactionCase):

    def test_report_returns_accounts_and_totals(self):
        report = self.env['cash.book.report'].view_report()

        self.assertIn('accounts', report)
        self.assertIn('move_lines_total', report)
        self.assertIsInstance(report['accounts'], list)
