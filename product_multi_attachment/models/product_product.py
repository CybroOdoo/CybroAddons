from odoo import fields, models


class ProductProduct(models.Model):
    """Inherits product.product to add variant-specific attachments."""

    _inherit = 'product.product'

    attachment_ids = fields.Many2many(
        'ir.attachment',
        string='Attachments',
        help='Attachments linked specifically to this product variant.',
    )
