from odoo import fields, models


class ResUsers(models.Model):
    """Adds the per-user refresh option."""
    _inherit = 'res.users'

    is_refresh = fields.Boolean(
        string='Refresh Views', default=False,
        help='Show the refresh button on list and kanban views.')

    @property
    def SELF_WRITEABLE_FIELDS(self):
        return list(super().SELF_WRITEABLE_FIELDS) + ['is_refresh']