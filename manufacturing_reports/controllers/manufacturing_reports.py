import json
from werkzeug.exceptions import BadRequest
from odoo import http
from odoo.http.stream import content_disposition, request
from odoo.tools import html_escape

ALLOWED_MODELS = {'mrp.report.wizard'}


class XLSXReportController(http.Controller):
    """Controller for generating and downloading XLSX reports."""
    @http.route('/xlsx_reports', type='http', auth='user', methods=['POST'], csrf=False)
    def get_report_xlsx(self, model, options, output_format, report_name, **kw):
        """Generate an XLSX report and return it as an HTTP response."""
        if model not in ALLOWED_MODELS or model not in request.env:
            raise BadRequest("Invalid report model")
        uid = request.session.uid
        report_obj = request.env[model].with_user(uid)
        options = json.loads(options)
        token = 'dummy-because-api-expects-one'
        try:
            if output_format == 'xlsx':
                response = request.make_response(
                    None,
                    headers=[
                        ('Content-Type', 'application/vnd.ms-excel'),
                        ('Content-Disposition',
                         content_disposition(report_name + '.xlsx'))
                    ]
                )
                report_obj.get_xlsx_report(options, response)
                response.set_cookie('fileToken', token)
                return response
        except Exception as e:
            se = http.serialize_exception(e)
            error = {
                'code': 200,
                'message': 'Odoo Server Error',
                'data': se
            }
            return request.make_response(html_escape(json.dumps(error)))
