class ProjectProjectStage(models.Model):
    """
    Extends 'project.project.stage' to flag stages specifically designated 
    for oil reservoir lifecycle management.
    """
    _inherit = 'project.project.stage'

    is_oil_project_stage = fields.Boolean(
        string='Is Reservoir Stage',
        help='If checked, this stage will be available for Oil Reservoirs.'
    )
