from odoo import fields, models
from odoo.exceptions import AccessError, UserError


class AiImageGenerationLog(models.Model):
    """Stores audit logs for AI image generation requests and results."""
    _name = 'ai.image.generation.log'
    _description = 'AI Image Generation Log'
    _order = 'create_date desc'
    _rec_name = 'product_id'

    product_id = fields.Many2one(
        'product.template',
        ondelete='set null',
        index=True,
    )
    user_id = fields.Many2one(
        'res.users',
        string='Generated By',
        default=lambda self: self.env.user,
        readonly=True,
    )
    prompt = fields.Text(string='Prompt Used', readonly=True)
    ai_provider = fields.Selection(
        selection=[
            ('openai', 'OpenAI DALL-E 3'),
            ('stability', 'Stability AI'),
            ('gemini', 'Google Gemini'),
        ],
        string='AI Provider',
        readonly=True,
    )
    image_style = fields.Selection(
        selection=[
            ('professional', 'Professional Product Photo'),
            ('lifestyle', 'Lifestyle / In Context'),
            ('minimal', 'Minimal / White Background'),
            ('artistic', 'Artistic / Creative'),
        ],
        readonly=True,
    )
    status = fields.Selection(
        selection=[
            ('success', 'Success'),
            ('failed', 'Failed'),
            ('pending_approval', 'Pending Approval'),
            ('rejected', 'Rejected'),
        ],
        default='success',
        readonly=True,
    )
    image_generated = fields.Binary(
        string='Generated Image',
        attachment=True,
    )
    image_applied = fields.Boolean(
        string='Applied to Product',
        default=False,
        readonly=True,
    )
    enhance_mode = fields.Boolean(
        default=False,
        readonly=True,
    )
    error_message = fields.Text(
        readonly=True,
    )
    num_variants_requested = fields.Integer(
        string='Variants Requested',
        readonly=True,
    )
    image_size = fields.Char(
        readonly=True,
    )
    approved_by_id = fields.Many2one(
        'res.users',
        string='Reviewed By',
        readonly=True,
    )
    approved_date = fields.Datetime(
        string='Reviewed On',
        readonly=True,
    )

    def _check_manager_access(self):
        """Ensure only AI Image Generator Managers can approve or reject images."""
        if not self.env.su and not self.env.user.has_group(
            'smart_product_image_generator.group_ai_image_manager'
        ):
            raise AccessError(
                self.env._(
                    'Only AI Image Generator Managers can approve or reject images.'
                )
            )

    def action_approve(self):
        """Approve pending log(s) and apply the generated image to the product."""
        self._check_manager_access()
        for rec in self:
            if rec.status != 'pending_approval':
                raise UserError(
                    self.env._(
                        'Only logs with "Pending Approval" status can be approved.'
                    )
                )
            if not rec.product_id:
                raise UserError(
                    self.env._(
                        'Cannot approve: the linked product no longer exists.'
                    )
                )
            if not rec.image_generated:
                raise UserError(
                    self.env._(
                        'Cannot approve: no generated image is attached to this log.'
                    )
                )
            fields_desc = rec.fields_get(['ai_provider', 'image_style'])
            provider_labels = dict(fields_desc['ai_provider']['selection'])
            style_labels = dict(fields_desc['image_style']['selection'])
            rec.product_id._apply_ai_generated_image(
                image_data=rec.image_generated,
                provider_label=provider_labels.get(
                    rec.ai_provider, rec.ai_provider or ''
                ),
                style_label=style_labels.get(
                    rec.image_style, rec.image_style or ''
                ),
                size=rec.image_size or '',
            )
            rec.write({
                'status': 'success',
                'image_applied': True,
                'approved_by_id': self.env.user.id,
                'approved_date': fields.Datetime.now(),
            })
        return True

    def action_reject(self):
        """Reject pending log(s) without applying the image to the product."""
        self._check_manager_access()
        for rec in self:
            if rec.status != 'pending_approval':
                raise UserError(
                    self.env._(
                        'Only logs with "Pending Approval" status can be rejected.'
                    )
                )
            rec.write({
                'status': 'rejected',
                'image_applied': False,
                'approved_by_id': self.env.user.id,
                'approved_date': fields.Datetime.now(),
            })
        return True
