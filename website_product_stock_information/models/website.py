from odoo import fields, models

class Website(models.Model):
    _inherit = 'website'

    shop_show_product_stock_info = fields.Boolean(default=False,string="Product Stock")

    def _get_website_configurable_fields(self):
        fields = super()._get_website_configurable_fields()
        fields.append('shop_show_product_stock_info')
        return fields