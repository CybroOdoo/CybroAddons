from odoo import Command, fields
from odoo.addons.account.tests.common import AccountTestInvoicingCommon
from odoo.tests.common import tagged


@tagged('post_install', '-at_install')
class TestAccountMove(AccountTestInvoicingCommon):
    """Unit tests for discount journal entries generated by account.move."""

    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        cls.company = cls.company_data['company']

        # Pure numeric account codes without dashes to adhere to Odoo 20 account code constraints
        cls.customer_discount_account = cls.env['account.account'].create({
            'code': '999001',
            'name': 'Customer Discount Account',
            'account_type': 'expense',
            'company_ids': [Command.link(cls.company.id)],
        })
        cls.vendor_discount_account = cls.env['account.account'].create({
            'code': '999002',
            'name': 'Vendor Discount Account',
            'account_type': 'income_other',
            'company_ids': [Command.link(cls.company.id)],
        })

        cls.category_with_discount = cls.env['product.category'].create({
            'name': 'Category With Discount',
            'customer_account_discount_id': cls.customer_discount_account.id,
            'vendor_account_discount_id': cls.vendor_discount_account.id,
            'property_account_income_categ_id': cls.company_data['default_account_revenue'].id,
            'property_account_expense_categ_id': cls.company_data['default_account_expense'].id,
        })
        cls.category_without_discount = cls.env['product.category'].create({
            'name': 'Category Without Discount',
            'property_account_income_categ_id': cls.company_data['default_account_revenue'].id,
            'property_account_expense_categ_id': cls.company_data['default_account_expense'].id,
        })

        cls.product_with_discount = cls.env['product.product'].create({
            'name': 'Discounted Product',
            'type': 'consu',
            'list_price': 100.0,
            'standard_price': 80.0,
            'categ_id': cls.category_with_discount.id,
        })
        cls.product_without_discount = cls.env['product.product'].create({
            'name': 'Regular Product',
            'type': 'consu',
            'list_price': 50.0,
            'categ_id': cls.category_without_discount.id,
        })

        cls.partner = cls.partner_a

        # Secondary currency for multi-currency tests
        cls.currency_eur = cls.env.ref('base.EUR', raise_if_not_found=False)
        if cls.currency_eur and not cls.currency_eur.active:
            cls.currency_eur.active = True

        # Tax-included tax for testing tax-included discount computation
        cls.tax_included = cls.env['account.tax'].create({
            'name': '15% Tax Included',
            'amount_type': 'percent',
            'amount': 15.0,
            'price_include_override': 'tax_included',
            'company_id': cls.company.id,
        })

    def test_action_post(self):
        """Test action_post creates balanced category discount lines for invoices, bills, refunds,
        tax-included lines, and multi-currency moves.
        """
        # 1. Customer Invoice (out_invoice) with quantity = 2, unit price = 100, discount = 10%
        # Undiscounted: 200. Discount amount: 20. Net subtotal: 180.
        invoice = self.env['account.move'].create({
            'move_type': 'out_invoice',
            'partner_id': self.partner.id,
            'invoice_date': fields.Date.today(),
            'invoice_line_ids': [
                Command.create({
                    'product_id': self.product_with_discount.id,
                    'quantity': 2.0,
                    'price_unit': 100.0,
                    'discount': 10.0,
                    'tax_ids': False,
                }),
            ],
        })
        invoice.action_post()
        self.assertEqual(invoice.state, 'posted')

        discount_lines = invoice.line_ids.filtered(
            lambda l: l.is_discount_journal_entry or l.display_type == 'category_discount'
        )
        self.assertEqual(len(discount_lines), 2)
        debit_line = discount_lines.filtered(lambda l: l.debit > 0)
        credit_line = discount_lines.filtered(lambda l: l.credit > 0)
        self.assertEqual(len(debit_line), 1)
        self.assertEqual(len(credit_line), 1)

        # Expected discount amount is 20.0
        self.assertAlmostEqual(debit_line.debit, 20.0)
        self.assertAlmostEqual(credit_line.credit, 20.0)
        self.assertEqual(debit_line.account_id, self.customer_discount_account)
        self.assertEqual(credit_line.account_id, invoice.invoice_line_ids.account_id)
        self.assertEqual(debit_line.amount_currency, 20.0)
        self.assertEqual(credit_line.amount_currency, -20.0)
        self.assertEqual(debit_line.display_type, 'category_discount')
        self.assertTrue(debit_line.is_discount_journal_entry)
        self.assertAlmostEqual(sum(invoice.line_ids.mapped('debit')), sum(invoice.line_ids.mapped('credit')))

        # 2. Customer Refund (out_refund)
        credit_note = self.env['account.move'].create({
            'move_type': 'out_refund',
            'partner_id': self.partner.id,
            'invoice_date': fields.Date.today(),
            'invoice_line_ids': [
                Command.create({
                    'product_id': self.product_with_discount.id,
                    'quantity': 2.0,
                    'price_unit': 100.0,
                    'discount': 10.0,
                    'tax_ids': False,
                }),
            ],
        })
        credit_note.action_post()
        cn_discount_lines = credit_note.line_ids.filtered(
            lambda l: l.is_discount_journal_entry or l.display_type == 'category_discount'
        )
        self.assertEqual(len(cn_discount_lines), 2)
        cn_debit_line = cn_discount_lines.filtered(lambda l: l.debit > 0)
        cn_credit_line = cn_discount_lines.filtered(lambda l: l.credit > 0)
        self.assertEqual(cn_debit_line.account_id, credit_note.invoice_line_ids.account_id)
        self.assertEqual(cn_credit_line.account_id, self.customer_discount_account)
        self.assertAlmostEqual(cn_debit_line.debit, 20.0)
        self.assertAlmostEqual(cn_credit_line.credit, 20.0)

        # 3. Vendor Bill (in_invoice)
        bill = self.env['account.move'].create({
            'move_type': 'in_invoice',
            'partner_id': self.partner.id,
            'invoice_date': fields.Date.today(),
            'invoice_line_ids': [
                Command.create({
                    'product_id': self.product_with_discount.id,
                    'quantity': 3.0,
                    'price_unit': 50.0,
                    'discount': 20.0,
                    'tax_ids': False,
                }),
            ],
        })
        bill.action_post()
        bill_discount_lines = bill.line_ids.filtered(
            lambda l: l.is_discount_journal_entry or l.display_type == 'category_discount'
        )
        self.assertEqual(len(bill_discount_lines), 2)
        bill_debit_line = bill_discount_lines.filtered(lambda l: l.debit > 0)
        bill_credit_line = bill_discount_lines.filtered(lambda l: l.credit > 0)
        # Expected discount: 3 * 50 * 20% = 30.0
        self.assertAlmostEqual(bill_debit_line.debit, 30.0)
        self.assertAlmostEqual(bill_credit_line.credit, 30.0)
        self.assertEqual(bill_debit_line.account_id, bill.invoice_line_ids.account_id)
        self.assertEqual(bill_credit_line.account_id, self.vendor_discount_account)

        # 4. Vendor Refund (in_refund)
        bill_refund = self.env['account.move'].create({
            'move_type': 'in_refund',
            'partner_id': self.partner.id,
            'invoice_date': fields.Date.today(),
            'invoice_line_ids': [
                Command.create({
                    'product_id': self.product_with_discount.id,
                    'quantity': 1.0,
                    'price_unit': 50.0,
                    'discount': 10.0,
                    'tax_ids': False,
                }),
            ],
        })
        bill_refund.action_post()
        refund_discount_lines = bill_refund.line_ids.filtered(
            lambda l: l.is_discount_journal_entry or l.display_type == 'category_discount'
        )
        self.assertEqual(len(refund_discount_lines), 2)
        refund_debit = refund_discount_lines.filtered(lambda l: l.debit > 0)
        refund_credit = refund_discount_lines.filtered(lambda l: l.credit > 0)
        self.assertEqual(refund_debit.account_id, self.vendor_discount_account)
        self.assertEqual(refund_credit.account_id, bill_refund.invoice_line_ids.account_id)

        # 5. Tax-included price discount handling
        tax_inv = self.env['account.move'].create({
            'move_type': 'out_invoice',
            'partner_id': self.partner.id,
            'invoice_date': fields.Date.today(),
            'invoice_line_ids': [
                Command.create({
                    'product_id': self.product_with_discount.id,
                    'quantity': 1.0,
                    'price_unit': 115.0,  # 115 with 15% tax included -> 100 net base
                    'discount': 10.0,     # 10% of 100 = 10.0 discount
                    'tax_ids': [Command.set(self.tax_included.ids)],
                }),
            ],
        })
        tax_inv.action_post()
        tax_discount_lines = tax_inv.line_ids.filtered(
            lambda l: l.is_discount_journal_entry or l.display_type == 'category_discount'
        )
        self.assertEqual(len(tax_discount_lines), 2)
        tax_debit = tax_discount_lines.filtered(lambda l: l.debit > 0)
        tax_credit = tax_discount_lines.filtered(lambda l: l.credit > 0)
        # Base net of tax is 100, 10% discount is 10.0
        self.assertAlmostEqual(tax_debit.debit, 10.0)
        self.assertAlmostEqual(tax_credit.credit, 10.0)
        self.assertAlmostEqual(sum(tax_inv.line_ids.mapped('debit')), sum(tax_inv.line_ids.mapped('credit')))

        # 6. Multi-currency foreign invoice
        if self.currency_eur and self.currency_eur != self.company.currency_id:
            foreign_invoice = self.env['account.move'].create({
                'move_type': 'out_invoice',
                'partner_id': self.partner.id,
                'currency_id': self.currency_eur.id,
                'invoice_date': fields.Date.today(),
                'invoice_line_ids': [
                    Command.create({
                        'product_id': self.product_with_discount.id,
                        'quantity': 2.0,
                        'price_unit': 100.0,
                        'discount': 10.0,
                        'tax_ids': False,
                    }),
                ],
            })
            foreign_invoice.action_post()
            f_discount_lines = foreign_invoice.line_ids.filtered(
                lambda l: l.is_discount_journal_entry or l.display_type == 'category_discount'
            )
            self.assertEqual(len(f_discount_lines), 2)
            f_debit = f_discount_lines.filtered(lambda l: l.debit > 0)
            f_credit = f_discount_lines.filtered(lambda l: l.credit > 0)
            # 2 * 100 * 10% = 20 EUR
            self.assertEqual(f_debit.amount_currency, 20.0)
            self.assertEqual(f_credit.amount_currency, -20.0)
            self.assertEqual(f_debit.currency_id, self.currency_eur)
            self.assertEqual(f_credit.currency_id, self.currency_eur)
            inv_line = foreign_invoice.invoice_line_ids[0]
            expected_balance = inv_line.company_currency_id.round(
                20.0 / inv_line.currency_rate
            ) if inv_line.currency_rate else inv_line.currency_id._convert(
                20.0,
                inv_line.company_currency_id,
                inv_line.company_id,
                foreign_invoice.date or fields.Date.today(),
            )
            self.assertAlmostEqual(f_debit.debit, expected_balance)
            self.assertAlmostEqual(f_credit.credit, expected_balance)
            self.assertAlmostEqual(
                sum(foreign_invoice.line_ids.mapped('debit')),
                sum(foreign_invoice.line_ids.mapped('credit')),
            )

    def test_button_draft(self):
        """Test reset to draft unlinks discount lines and re-posting does not duplicate them."""
        invoice = self.env['account.move'].create({
            'move_type': 'out_invoice',
            'partner_id': self.partner.id,
            'invoice_date': fields.Date.today(),
            'invoice_line_ids': [
                Command.create({
                    'product_id': self.product_with_discount.id,
                    'quantity': 1.0,
                    'price_unit': 100.0,
                    'discount': 15.0,
                    'tax_ids': False,
                }),
            ],
        })
        invoice.action_post()
        self.assertEqual(
            len(invoice.line_ids.filtered(
                lambda l: l.is_discount_journal_entry or l.display_type == 'category_discount'
            )),
            2,
        )

        # Reset to draft
        invoice.button_draft()
        self.assertEqual(invoice.state, 'draft')
        # Custom discount lines must be unlinked
        self.assertEqual(
            len(invoice.line_ids.filtered(
                lambda l: l.is_discount_journal_entry or l.display_type == 'category_discount'
            )),
            0,
        )

        # Re-post the invoice
        invoice.action_post()
        self.assertEqual(invoice.state, 'posted')
        # Should have exactly 2 discount lines, no duplicates
        self.assertEqual(
            len(invoice.line_ids.filtered(
                lambda l: l.is_discount_journal_entry or l.display_type == 'category_discount'
            )),
            2,
        )

    def test_create_discount_lines(self):
        """Test _create_discount_lines ignores lines without discount or without discount accounts."""
        invoice = self.env['account.move'].create({
            'move_type': 'out_invoice',
            'partner_id': self.partner.id,
            'invoice_date': fields.Date.today(),
            'invoice_line_ids': [
                # Line with product having no discount account configured
                Command.create({
                    'product_id': self.product_without_discount.id,
                    'quantity': 1.0,
                    'price_unit': 100.0,
                    'discount': 10.0,
                    'tax_ids': False,
                }),
                # Line with 0% discount
                Command.create({
                    'product_id': self.product_with_discount.id,
                    'quantity': 1.0,
                    'price_unit': 100.0,
                    'discount': 0.0,
                    'tax_ids': False,
                }),
            ],
        })
        invoice._create_discount_lines()
        discount_lines = invoice.line_ids.filtered(
            lambda l: l.is_discount_journal_entry or l.display_type == 'category_discount'
        )
        self.assertEqual(len(discount_lines), 0)

    def test_button_cancel(self):
        """Test cancelling a posted invoice unlinks discount lines."""
        invoice = self.env['account.move'].create({
            'move_type': 'out_invoice',
            'partner_id': self.partner.id,
            'invoice_date': fields.Date.today(),
            'invoice_line_ids': [
                Command.create({
                    'product_id': self.product_with_discount.id,
                    'quantity': 1.0,
                    'price_unit': 100.0,
                    'discount': 10.0,
                    'tax_ids': False,
                }),
            ],
        })
        invoice.action_post()
        self.assertEqual(
            len(invoice.line_ids.filtered(
                lambda l: l.is_discount_journal_entry or l.display_type == 'category_discount'
            )),
            2,
        )
        invoice.button_cancel()
        self.assertEqual(invoice.state, 'cancel')
        self.assertEqual(
            len(invoice.line_ids.filtered(
                lambda l: l.is_discount_journal_entry or l.display_type == 'category_discount'
            )),
            0,
        )

