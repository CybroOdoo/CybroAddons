from odoo import fields, models


class PurchaseOrder(models.Model):
    """Links purchase orders to the tender they come from."""
    _inherit = 'purchase.order'

    tender_id = fields.Many2one('tender.management', string="Related Tender",
                                help="Tender this purchase order was created from.")
