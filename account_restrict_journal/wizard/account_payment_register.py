from odoo import api, models


class AccountPaymentRegister(models.TransientModel):
    """Hide the restricted journals from the register payment wizard."""
    _inherit = 'account.payment.register'

    @api.model
    def _get_batch_available_journals(self, batch_result):
        """Exclude the journals restricted for the current user."""
        journals = super()._get_batch_available_journals(batch_result)
        return journals - self.env.user.journal_ids
