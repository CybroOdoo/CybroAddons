from odoo import api, models


class Followers(models.Model):
    """Inherited mail follower model for adding a new function"""
    _inherit = "mail.followers"

    @api.model
    def get_partner(self, follower_id):
        """function for getting partner details"""
        partner_id = self.sudo().browse(follower_id).partner_id
        return partner_id.id, partner_id.name
