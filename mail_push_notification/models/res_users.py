from odoo import models


class ResUsers(models.Model):
    """Extend users with push notification permission helpers."""
    _inherit = 'res.users'

    def has_push_notification_permission(self):
        """Return whether the current user can receive push notifications."""
        return self.has_group('base.group_user')
