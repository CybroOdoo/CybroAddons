"""Delete the unused "Access to Accounting Dashboard" group.

The group was defined in the ``noupdate`` block of ``security/security.xml``
and used nowhere; Odoo does not delete removed no-update records on upgrade.
"""
import logging

from odoo import api, SUPERUSER_ID

_logger = logging.getLogger(__name__)


def migrate(cr, version):
    if not version:
        return
    env = api.Environment(cr, SUPERUSER_ID, {})
    group = env.ref('base_accounting_kit.group_account_dashboard',
                    raise_if_not_found=False)
    if group:
        group.unlink()
        _logger.info("Removed the unused group 'Access to Accounting "
                     "Dashboard'.")
