"""Asset history: rebuild the "Depreciation line posted" messages posted
as escaped HTML by earlier versions (P1.15), so they show formatted."""
import logging

from odoo import api, SUPERUSER_ID

_logger = logging.getLogger(__name__)


def migrate(cr, version):
    if not version:
        return
    env = api.Environment(cr, SUPERUSER_ID, {})
    fixed = env['account.asset.asset']._kit_fix_posted_messages()
    if fixed:
        _logger.info("Rebuilt %s asset messages shown as HTML code.", fixed)
