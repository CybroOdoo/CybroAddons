import json
import logging
import requests
from odoo import api, fields, models
from odoo.tools import html2plaintext

_logger = logging.getLogger(__name__)


class HelpdeskTicket(models.Model):
    _inherit = "helpdesk.ticket"

    sentiment_score = fields.Float(
        "Raw Sentiment Score",
        tracking=True,
        help="The raw sentiment score generated by the AI, ranging from -1.0 "
             "(Highly Negative) to 1.0 (Highly Positive). A score of 0.0 "
             "indicates a perfectly neutral tone."
    )
    sentiment_percent = fields.Integer(
        "Customer Mood (%)",
        compute="_compute_sentiment_percent",
        store=True,
        tracking=True,
        help="The AI sentiment score converted into a standard 0 to 100 "
             "percentage scale. 0% represents maximum frustration, 50% is "
             "neutral, and 100% is extremely satisfied."
    )
    sentiment_human = fields.Char(
        "Customer Mood",
        compute="_compute_sentiment_human",
        store=True,
        tracking=True,
        help="A human-readable label and emoji representing the customer's "
             "current emotional state, determined by the AI analysis."
    )

    risk_level = fields.Selection([
        ('low', 'Healthy'),
        ('medium', 'Attention Needed'),
        ('high', 'Critical'),
    ], default="low", tracking=True,
        help="The calculated churn risk level of this specific ticket. "
             "'Critical' tickets typically contain severe frustration and "
             "require immediate escalation.")

    is_high_risk = fields.Boolean(
        "High Risk",
        help="A technical flag indicating if this ticket is currently "
             "classified as 'Critical'. Used behind the scenes for dashboard "
             "filtering and automated alerts."
    )

    @api.depends('sentiment_score')
    def _compute_sentiment_percent(self):
        """Converts raw sentiment score (-1.0 to 1.0) into 0-100 percentage."""
        for ticket in self:
            ticket.sentiment_percent = max(
                0, min(100, int(round((ticket.sentiment_score + 1.0) * 50)))
            )


    @api.depends('sentiment_score')
    def _compute_sentiment_human(self):
        """Assigns a human-readable emotional label and emoji based on the raw
        sentiment score.
        """
        for ticket in self:
            score = ticket.sentiment_score or 0
            if score <= -0.6:
                ticket.sentiment_human = "Very Frustrated 🔴"
            elif score <= -0.2:
                ticket.sentiment_human = "Unhappy 🟠"
            elif score <= 0.2:
                ticket.sentiment_human = "Neutral 🟡"
            elif score <= 0.6:
                ticket.sentiment_human = "Satisfied 🟢"
            else:
                ticket.sentiment_human = "Very Happy 🟢"

    @api.model_create_multi
    def create(self, vals_list):
        """Overrides ticket creation to automatically run AI sentiment
        analysis on the initial ticket description.
        """
        tickets = super().create(vals_list)
        for ticket in tickets:
            try:
                if not self.env['ir.config_parameter'].sudo().get_bool(
                        'customer_success_sentiment_tracker.enable_ai'):
                    continue
                is_internal_partner = False
                if ticket.partner_id and ticket.partner_id.user_ids:
                    if any(not u.share for u in ticket.partner_id.user_ids):
                        is_internal_partner = True

                if not is_internal_partner and ticket.description:
                    ticket._run_sentiment_analysis(ticket.description)
            except Exception as e:
                _logger.error("Error in AI Ticket Create: %s", e)
        return tickets

    def action_analyze_sentiment(self):
        """Allows users to manually trigger AI sentiment analysis on the ticket
        description or chatter messages.
        """
        for ticket in self:
            text_to_analyze = ticket.description
            if not text_to_analyze:
                messages = ticket.message_ids.filtered(
                    lambda m: m.message_type in ('email', 'comment') and m.body
                )
                if messages:
                    text_to_analyze = messages[0].body
            if text_to_analyze:
                ticket._run_sentiment_analysis(text_to_analyze)

    def message_post(self, **kwargs):
        """Overrides chatter posting to intercept incoming customer replies and
        analyze their sentiment.
        """
        message = super().message_post(**kwargs)
        try:
            if not self.env['ir.config_parameter'].sudo().get_bool(
                    'customer_success_sentiment_tracker.enable_ai'):
                return message
            for ticket in self:
                if (
                    not message
                    or message.message_type not in ('email', 'comment')
                ):
                    continue
                if message.subtype_id and message.subtype_id.internal:
                    continue

                is_internal = False
                author = message.author_id
                if author:
                    if (
                        author.user_ids
                        and any(not u.share for u in author.user_ids)
                    ):
                        is_internal = True

                if is_internal or not message.body:
                    continue
                ticket._run_sentiment_analysis(message.body)
        except Exception as e:
            _logger.error("Error in AI Message Post: %s", e)
        return message

    def _extract_json(self, content):
        """Safely extracts and parses a JSON dictionary from a raw string
        returned by the OpenAI API.
        """
        try:
            start = content.find('{')
            end = content.rfind('}')
            if start == -1 or end == -1:
                return None
            return json.loads(content[start:end + 1])
        except Exception as e:
            _logger.error("JSON parsing failed: %s", e)
            return None

    def _run_sentiment_analysis(self, body):
        """Sends the provided text to OpenAI for sentiment analysis and updates
        the ticket's scores accordingly.
        """
        config = self.env['ir.config_parameter'].sudo()
        api_key = config.get_str(
            'customer_success_sentiment_tracker.openai_api_key'
        )
        model = config.get_str(
            'customer_success_sentiment_tracker.model_id'
        ) or 'gpt-4o-mini'

        if not api_key:
            _logger.warning(
                "Sentiment Analysis skipped: OpenAI API Key is missing."
            )
            return
        text = html2plaintext(body)
        if not text.strip():
            _logger.warning("Sentiment Analysis skipped: Empty text body.")
            return

        prompt = f"""Analyze the sentiment of the following customer message.
        Return strictly raw JSON with no markdown formatting:
        {{"score": float between -1 and 1}}
        Message:
        {text}
        """

        try:
            payload = {
                "model": model,
                "messages": [{"role": "user", "content": prompt}],
                "temperature": 0.2,
                "max_tokens": 100,
                "response_format": {"type": "json_object"}
            }
            response = requests.post(
                "https://api.openai.com/v1/chat/completions",
                headers={
                    "Authorization": f"Bearer {api_key}",
                    "Content-Type": "application/json"
                },
                json=payload,
                timeout=20
            )

            if response.status_code != 200:
                _logger.error(
                    "OpenAI API error %s: %s",
                    response.status_code,
                    response.text
                )
                return

            result = self._extract_json(
                response.json()['choices'][0]['message']['content']
            )
            if not result:
                _logger.error(
                    "Failed to parse JSON response from OpenAI: %s",
                    response.json()
                )
                return

            score = float(result.get("score", 0))
            risk = (
                'high' if score <= -0.6
                else 'medium' if score <= -0.2
                else 'low'
            )

            self.write({
                'sentiment_score': score,
                'risk_level': risk,
                'is_high_risk': risk == 'high'
            })

            if risk == 'high':
                self._create_high_risk_activity()

        except Exception as e:
            _logger.error("Sentiment analysis request failed: %s", e)

    def _create_high_risk_activity(self):
        """Schedules a high-priority To-Do activity for Helpdesk Managers when
        a ticket is flagged as Critical.
        """
        manager_group = self.env.ref(
            'helpdesk.group_helpdesk_manager', raise_if_not_found=False
        )
        if not manager_group:
            return
        for manager in manager_group.user_ids:
            self.activity_schedule(
                'mail.mail_activity_data_todo',
                user_id=manager.id,
                summary=self.env._("Critical Customer Detected"),
                note=self.env._(
                    "Customer sentiment classified as CRITICAL. "
                    "Immediate attention required."
                )
            )
