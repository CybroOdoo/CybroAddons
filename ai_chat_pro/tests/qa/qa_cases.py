def rec(created, model):
    return next((r for r in created if r._name == model), None)


def ok_lines(order, expected):
    """ expected: {product name part: qty} """
    lines = {(l.product_id.name or '').lower(): l.product_uom_qty for l in order.order_line}
    for name, qty in expected.items():
        if not any(name.lower() in key and abs(q - qty) < 0.01 for key, q in lines.items()):
            return f"lines {lines} lack {name}={qty}"
    return None


def inv_lines(move, expected):
    lines = {(l.product_id.name or '').lower(): l.quantity for l in move.invoice_line_ids}
    for name, qty in expected.items():
        if not any(name.lower() in key and abs(q - qty) < 0.01 for key, q in lines.items()):
            return f"lines {lines} lack {name}={qty}"
    return None


