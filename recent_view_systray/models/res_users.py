from odoo import fields, models


class ResUsers(models.Model):
    """
    Inherits from 'res.users' to add specific configuration for the
    recent view systray history limit.
    """
    _inherit = 'res.users'

    history_limit = fields.Integer(string='History Limit', default=15,
                                   help="Maximum number of recently visited views to display in the systray.")
