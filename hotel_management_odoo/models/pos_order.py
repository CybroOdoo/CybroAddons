from odoo import fields, models


class PosOrder(models.Model):
    """Link point of sale orders to hotel room bookings"""
    _inherit = "pos.order"

    booking_id = fields.Many2one('room.booking', string="Room Booking",
                                 help="Room booking this POS order belongs to",
                                 index='btree_not_null', copy=False)
