from odoo import fields, models


class HrEmployee(models.Model):
    """
    Extends the standard 'hr.employee' model to include oil industry specific
    fields, such as hourly wage for project-based cost calculations.
    """
    _inherit = 'hr.employee'

    hourly_wage = fields.Monetary(string='Hourly Wage',
                                  help="Enter the hourly Wage.")
