from odoo import models, fields


class IrModel(models.Model):
    """Extension of ir.model to mark OCR-enabled models."""
    _inherit = 'ir.model'

    is_ocr_tus = fields.Boolean(
        string="Is OCR Enabled",
        help='If checked, this model becomes selectable in OCR AI Configuration, '
             'allowing documents to be imported into it via OCR.',
    )