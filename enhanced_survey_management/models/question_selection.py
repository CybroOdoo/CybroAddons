from odoo import fields, models


class QuestionSelection(models.Model):
    """Model to store options for selection-type questions."""

    _name = 'question.selection'
    _description = 'Selection Question'

    name = fields.Char(help="Selection value.")
    question_id = fields.Many2one(
        'survey.question',
        help="Question associated with this selection option.",
    )
